/// Looks up a CITIES entry by key, english, or arabic name (case/space tolerant).
Map<String, dynamic>? cityInfoFor(String? city) {
  if (city == null || city.trim().isEmpty) return null;
  final trimmed = city.trim();
  final lower = trimmed.toLowerCase();
  final key = lower.replaceAll(' ', '');
  for (final entry in CITIES.entries) {
    final value = entry.value as Map<String, dynamic>;
    final english = (value['english'] as String?)?.toLowerCase();
    if (entry.key.toLowerCase() == key ||
        english == lower ||
        english?.replaceAll(' ', '') == key ||
        value['arabic'] == trimmed) {
      return value;
    }
  }
  return null;
}

